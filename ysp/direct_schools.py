def as_dicts() -> list[dict]:
    return [{"code": c, "name": n} for c, n in SCHOOLS]


def search(keyword: str = "") -> list[dict]:
    """按名称/代码模糊搜索；空关键词返回全部。"""
    q = (keyword or "").strip().lower()
    if not q:
        return as_dicts()
    hits = [{"code": c, "name": n} for c, n in SCHOOLS
            if q in n.lower() or q in c.lower()]
    # 前缀匹配的排前面
    hits.sort(key=lambda x: (not x["name"].lower().startswith(q), x["name"]))
    return hits


def resolve(text: str = "") -> tuple[str, str]:
    """把用户填的东西变成 (code, name)。

    接受：学校名称（完全一致）、学校代码、名称的唯一前缀。认不出就返回 ("", "")。
    """
    s = (text or "").strip()
    if not s:
        return "", ""
    low = s.lower()
    for c, n in SCHOOLS:
        if c.lower() == low:
            return c, n
    for c, n in SCHOOLS:
        if n == s:
            return c, n
    prefix = [(c, n) for c, n in SCHOOLS if n.lower().startswith(low)]
    if len(prefix) == 1:
        return prefix[0]
    return "", ""
